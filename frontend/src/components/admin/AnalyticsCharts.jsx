import React from 'react';
import { BarChart, Bar, XAxis, YAxis, Tooltip, ResponsiveContainer, CartesianGrid, PieChart, Pie, Cell, Legend } from 'recharts';
import { useTheme } from '../../context/ThemeContext';

const lightPalette = ['#4f46e5', '#6366f1', '#818cf8', '#a5b4fc', '#3730a3', '#312e81'];
const darkPalette = ['#a5b4fc', '#818cf8', '#6366f1', '#c7d2fe', '#4f46e5', '#3730a3'];

export default function AnalyticsCharts({ userActivity = [] }) {
    const { theme } = useTheme();
    const isDark = theme === 'dark';
    const palette = isDark ? darkPalette : lightPalette;
    const axisColor = isDark ? '#9ca3af' : '#6b7280';
    const gridColor = isDark ? '#374151' : '#e5e7eb';
    const borderColor = isDark ? '#374151' : '#d1d5db';
    const userChartData = userActivity.map((u) => ({
        user: u.email.split('@')[0],
        requests: u.total_requests,
    }));
    const latencyData = userActivity
        .filter((user) => user.keys?.some((key) => key.is_active)
            && Number.isFinite(Number(user.avg_latency_ms))
            && Number(user.avg_latency_ms) > 0)
        .map((user) => ({ user: user.email.split('@')[0], latency: Number(user.avg_latency_ms) }))
        .sort((a, b) => b.latency - a.latency);

    const tooltipStyle = {
        backgroundColor: isDark ? '#1f2937' : '#ffffff',
        borderColor: isDark ? '#374151' : '#e5e7eb',
        borderRadius: 8,
        color: isDark ? '#f9fafb' : '#1f2937',
    };

    return (
        <div className="grid grid-cols-1 lg:grid-cols-2 gap-4 sm:gap-6">
            <div className="bg-white border border-gray-200 rounded-xl p-6 shadow-sm">
                <h3 className="text-base font-semibold text-gray-900 mb-1">Requests by User</h3>
                <p className="text-sm text-gray-500 mb-4">Traffic generated by each user</p>
                <div className="h-56 sm:h-64 xl:h-72">
                    <ResponsiveContainer width="100%" height="100%">
                        <BarChart data={userChartData} margin={{ top: 8, right: 8, left: -16, bottom: 4 }}>
                            <CartesianGrid strokeDasharray="3 3" stroke={gridColor} vertical={false} />
                            <XAxis dataKey="user" tick={{ fill: axisColor, fontSize: 12 }} axisLine={{ stroke: borderColor }} tickLine={false} />
                            <YAxis allowDecimals={false} tick={{ fill: axisColor, fontSize: 12 }} axisLine={false} tickLine={false} />
                            <Tooltip contentStyle={tooltipStyle} formatter={(value) => [value, 'Requests']} />
                            <Bar dataKey="requests" name="Requests" fill={palette[0]} radius={[4, 4, 0, 0]} maxBarSize={44} />
                        </BarChart>
                    </ResponsiveContainer>
                </div>
            </div>

            <div className="bg-white border border-gray-200 rounded-xl p-6 shadow-sm">
                <h3 className="text-base font-semibold text-gray-900 mb-1">Average Latency by User</h3>
                <p className="text-sm text-gray-500 mb-4">Share of each user’s average response time</p>
                {latencyData.length ? (
                    <div className="h-56 sm:h-64 xl:h-72">
                        <ResponsiveContainer width="100%" height="100%">
                            <PieChart>
                                <Pie data={latencyData} dataKey="latency" nameKey="user" cx="50%" cy="48%" innerRadius={58} outerRadius={88} paddingAngle={2}>
                                    {latencyData.map((entry, index) => (
                                        <Cell key={entry.user} fill={palette[index % palette.length]} stroke={isDark ? '#1f2937' : '#ffffff'} />
                                    ))}
                                </Pie>
                                <Tooltip contentStyle={tooltipStyle} formatter={(value) => [`${Number(value).toFixed(2)} ms`, 'Avg latency']} />
                                <Legend verticalAlign="bottom" height={32} wrapperStyle={{ color: axisColor, fontSize: 12 }} />
                            </PieChart>
                        </ResponsiveContainer>
                    </div>
                ) : (
                    <div className="h-56 sm:h-64 xl:h-72 flex items-center justify-center rounded-lg border border-dashed border-gray-200 bg-gray-50 px-6 text-center">
                        <p className="max-w-sm text-sm text-gray-500">Latency data will appear after users generate API requests.</p>
                    </div>
                )}
            </div>
        </div>
    );
}
